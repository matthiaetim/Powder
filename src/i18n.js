const DICT = { de: DE, en: EN, es: ES, ja: JA };

// Ohne gespeicherte Wahl die Sprache des Geräts, sofern die App sie kennt, sonst Deutsch
function detect() {
  const saved = loadLang();
  if (LANGS.includes(saved)) return saved;
  const nav = typeof navigator !== 'undefined' ? navigator.languages || [navigator.language] : [];
  for (const l of nav) {
    const id = String(l || '').slice(0, 2).toLowerCase();
    if (LANGS.includes(id)) return id;
  }
  return 'de';
}

let lang = detect();
const listeners = [];

export const getLang = () => lang;

export function setLang(id) {
  if (!LANGS.includes(id) || id === lang) return false;
  lang = id;
  saveLang(id);
  formats.clear();
  for (const fn of listeners) fn(id);
  return true;
}

export const onLang = (fn) => { listeners.push(fn); };

export function t(key, vars) {
  let s = DICT[lang][key] ?? DE[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v));
  return s;
}

// Zahlformate je Sprache und Nachkommastellen, einmal gebaut: render.js formatiert Schilder in jedem Bild
const formats = new Map();
export function num(v, maxFrac = 0, minFrac = 0) {
  const key = maxFrac * 10 + minFrac;
  let f = formats.get(key);
  if (!f) { f = new Intl.NumberFormat(LOCALE[lang], { maximumFractionDigits: maxFrac, minimumFractionDigits: minFrac }); formats.set(key, f); }
  return f.format(v);
}
// Dezimaltrenner der Uhr (41,27 oder 41.27)
export const sep = () => (lang === 'de' || lang === 'es' ? ',' : '.');

// Statische Texte in index.html (data-t, data-t-ph, data-t-aria) und die Sprache des Dokuments
export function applyStatic(doc) {
  doc.documentElement.lang = lang;
  for (const el of doc.querySelectorAll('[data-t]')) el.textContent = t(el.dataset.t);
  for (const el of doc.querySelectorAll('[data-t-ph]')) el.placeholder = t(el.dataset.tPh);
  for (const el of doc.querySelectorAll('[data-t-aria]')) el.setAttribute('aria-label', t(el.dataset.tAria));
}
